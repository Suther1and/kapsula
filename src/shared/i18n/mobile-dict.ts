export function isKnownLocalizedMobileMessage(text: string, locale: AppLocale): boolean {
  if (KNOWN_DICT_MESSAGES[locale].has(text)) return true;
  return MEDIA_PREFIXES[locale].some((prefix) => text.startsWith(prefix));
}

